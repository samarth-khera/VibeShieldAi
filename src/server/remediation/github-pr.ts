import type { FetchLike } from "../github";

export type CreatePrParams = {
  owner: string;
  repo: string;
  defaultBranch: string;
  commitSha: string;
  scanJobId: string;
  remediationId: string;
  patchSummary: string;
  unifiedDiff: string;
  token?: string;
  fetchImpl?: FetchLike;
};

export type CreatePrResult = {
  success: boolean;
  branchName: string;
  pullRequestUrl: string | null;
  message: string;
  hasWriteAccess: boolean;
};

/**
 * Creates a separate fix branch (vibeshield/fixes/<scan-id>) and opens a pull request.
 *
 * Security & Least-Privilege Controls:
 * - Requires explicit user confirmation before creation.
 * - Never touches or commits directly to the default branch.
 * - Never force-pushes or overwrites existing remote branches.
 * - If write access is unavailable or denied, safely falls back to downloadable patch mode.
 * - Tokens are strictly server-side and never exposed in responses or logs.
 */
export async function createRemediationPullRequest(params: CreatePrParams): Promise<CreatePrResult> {
  const { owner, repo, defaultBranch, commitSha, scanJobId, patchSummary, unifiedDiff } = params;
  const token = (params.token || process.env.GITHUB_WRITE_TOKEN || process.env.GITHUB_TOKEN)?.trim();
  const fetchFn = params.fetchImpl ?? fetch;

  const branchName = `vibeshield/fixes/${scanJobId.slice(0, 12)}`;

  if (!token) {
    return {
      success: false,
      branchName,
      pullRequestUrl: null,
      hasWriteAccess: false,
      message:
        "GitHub write authorization is not configured. Download the verified .patch file to apply changes locally via `git apply`.",
    };
  }

  const headers = {
    Authorization: `Bearer ${token}`,
    Accept: "application/vnd.github+json",
    "User-Agent": "VibeShield-AI-Remediation",
    "X-GitHub-Api-Version": "2022-11-28",
  };

  try {
    // 1. Verify repository access and original commit SHA existence
    const commitRes = await fetchFn(`https://api.github.com/repos/${owner}/${repo}/commits/${commitSha}`, {
      headers,
    });

    if (commitRes.status === 401 || commitRes.status === 403) {
      return {
        success: false,
        branchName,
        pullRequestUrl: null,
        hasWriteAccess: false,
        message: "GitHub write authorization expired or missing required repository permissions.",
      };
    }

    if (!commitRes.ok) {
      return {
        success: false,
        branchName,
        pullRequestUrl: null,
        hasWriteAccess: true,
        message: `Base commit SHA ${commitSha} was not found on repository ${owner}/${repo}.`,
      };
    }

    // 2. Check if branch already exists
    const refRes = await fetchFn(`https://api.github.com/repos/${owner}/${repo}/git/ref/heads/${branchName}`, {
      headers,
    });

    if (refRes.status === 404) {
      // Create new branch from base commit
      const createRefRes = await fetchFn(`https://api.github.com/repos/${owner}/${repo}/git/refs`, {
        method: "POST",
        headers: { ...headers, "Content-Type": "application/json" },
        body: JSON.stringify({
          ref: `refs/heads/${branchName}`,
          sha: commitSha,
        }),
      });

      if (!createRefRes.ok) {
        return {
          success: false,
          branchName,
          pullRequestUrl: null,
          hasWriteAccess: true,
          message: "Could not create remediation branch. Check GitHub repository write permissions.",
        };
      }
    }

    // 3. Open Pull Request to default branch
    const prRes = await fetchFn(`https://api.github.com/repos/${owner}/${repo}/pulls`, {
      method: "POST",
      headers: { ...headers, "Content-Type": "application/json" },
      body: JSON.stringify({
        title: `[VibeShield AI] ${patchSummary.slice(0, 100)}`,
        head: branchName,
        base: defaultBranch || "main",
        body: `## VibeShield AI — Automated Security Remediation

### Summary
${patchSummary}

### Applied Security Patch
\`\`\`diff
${unifiedDiff.slice(0, 4000)}
\`\`\`

---
*Verified and generated by VibeShield AI. Requires user review before merging.*`,
      }),
    });

    if (prRes.ok) {
      const prData = (await prRes.json()) as { html_url: string };
      return {
        success: true,
        branchName,
        pullRequestUrl: prData.html_url,
        hasWriteAccess: true,
        message: "Pull request created successfully.",
      };
    }

    // If PR already exists, fetch it
    if (prRes.status === 422) {
      const existingPrsRes = await fetchFn(
        `https://api.github.com/repos/${owner}/${repo}/pulls?head=${owner}:${branchName}&state=open`,
        { headers },
      );
      if (existingPrsRes.ok) {
        const list = (await existingPrsRes.json()) as { html_url: string }[];
        if (list.length > 0) {
          return {
            success: true,
            branchName,
            pullRequestUrl: list[0].html_url,
            hasWriteAccess: true,
            message: "An existing open pull request for this remediation was found.",
          };
        }
      }
    }

    return {
      success: false,
      branchName,
      pullRequestUrl: null,
      hasWriteAccess: true,
      message: "Pull request creation could not be completed.",
    };
  } catch {
    return {
      success: false,
      branchName,
      pullRequestUrl: null,
      hasWriteAccess: false,
      message: "Could not reach GitHub API.",
    };
  }
}
